read_WTW <- function(project_dir) {
  project_name <- str_split(list.files(path = file.path(project_dir, "WTW"), pattern = "*.shp"), "\\.")[[1]][[1]]
  spatial_data <- st_read(file.path(project_dir, "WTW"), project_name)
  attribute_data <- st_read(file.path(project_dir, "Regional/Extractions/planning_unit_values.shp"))

  boundary_data <- tibble::as_tibble(
    utils::read.table(
      file.path(project_dir, "WTW", paste0(project_name, "_boundary.csv.gz")),
      stringsAsFactors = FALSE, sep = ",", header = TRUE,
      comment.char = "", quote = "\""
    )
  )

  metadata <- tibble::as_tibble(
    utils::read.table(
      file.path(project_dir, "WTW", "metadata", paste0(project_name, "_metadata.csv")),
      stringsAsFactors = FALSE, sep = ",", header = TRUE,
      comment.char = "", quote = "\""
    )
  )

  list(
    "spatial_data" = spatial_data,
    "attribute_data" = attribute_data,
    "boundary_data" = boundary_data,
    "metadata" = metadata
  )
}

prioritizr_solve_safe <- function(problem_obj, problem_data, n_portfolio) {
  tryCatch(
    expr = {
      scen_sol <- solve(problem_obj, force = TRUE)
      scen_sol # return solution
    },
    error = function(e) {
      print(paste0("Prioritizr optimization failed for one or more target runs"))
      NA # return NA
    }
  )
}

target_sweep <- function(problem_data, theme_ids, which_targets, feature_weights, sweep_bounds = c(0, 1), n = 99, n_portfolio = 1,
                         use_includes = FALSE, use_excludes = FALSE, sweep_type = "linear", weighting_method = "target") {
  # Compute MILP solution portfolios over a grid of coverage targets
  #
  # problem_data contains all feature data
  # theme_ids specifies the names of features to include in computation
  # which_targets identifies the indices of these features
  # feature_weights is a matrix of weights assigned to each feature in the optimization objective (usually all equal, unless otherwise specified)
  # sweep_bounds gives the lower and upper limits of the range of coverage targets to be swept over. Depending on the value of sweep_type, these may specify the limits themselves or the natural logarithms of the limits.
  # n is the number points populating the grid of coverage targets between the specified bounds
  # n_portfolio is the number of near-optimal solutions to compute (and average) for each coverage target
  # use_includes is a boolean specifying whether designated areas should be "locked in" to Prioritizr solutions
  # use_excludes is a boolean specifying whether designated areas should be "locked out" of Prioritizr solutions
  # sweep_type determines the spacing of the grid of coverage targets. Options are:
  #     'linear' : evenly-spaced grid points
  #     'exponential' : grid points generated by an exponential function, such that lower target values are more densely sampled than higher ones
  #     'lin-exp' : a grid produced by overlaying both above methods, to ensure dense sampling at low values without overly sparsifying high ones
  # weighting_method determines how feature weights are implemented:
  #     'target' : weights are applied by adjusting the coverage targets for each feature according to their weights
  #     'weight' : weights are implemented conventionally, as coefficients in the optimization objective function

  empty_cols <- c()
  for (tid in theme_ids) {
    if (sum(problem_data[tid] |> st_drop_geometry()) == 0) {
      empty_cols <- c(empty_cols, tid)
    }
  }

  if (length(empty_cols) > 0) {
    print("Omitting empty features from optimization:")
    print(empty_cols)

    theme_ids <- theme_ids[!(theme_ids %in% empty_cols)]
    which_targets <- which_targets[!rownames(which_targets) %in% empty_cols, ]
    feature_weights <- feature_weights[!rownames(feature_weights) %in% empty_cols, ]
  }

  if (sweep_type == "linear") {
    target_list <- seq(sweep_bounds[1], sweep_bounds[2], length.out = n + 2)
    target_list <- target_list[-c(1, n + 2)] # remove 0 and 1
  } else if (sweep_type == "exponential") {
    target_list <- exp(seq(sweep_bounds[1], sweep_bounds[2], length.out = n + 1))
    target_list <- target_list[-c(n + 1)] # remove 1
  } else if (sweep_type == "lin_exp") { # use exponential sweep_bounds
    target_list_lin <- seq(exp(sweep_bounds[1]), exp(sweep_bounds[2]), length.out = round(n / 2) + 2)
    target_list_lin <- target_list_lin[-c(1, round(n / 2) + 2)] # remove 0 and 1
    target_list_exp <- exp(seq(sweep_bounds[1], sweep_bounds[2], length.out = round(n / 2) + 1))
    target_list_exp <- target_list_exp[-c(round(n / 2) + 1)] # remove 1

    target_list <- append(target_list_lin, target_list_exp) |> sort(decreasing = FALSE)
  }

  target_midpoints <- 0.5 * (target_list[seq(1, length(target_list) - 1)] + target_list[seq(2, length(target_list))])
  target_midpoints_pad <- append(0, target_midpoints)
  if (sweep_type == "linear") {
    target_midpoints_pad <- append(target_midpoints_pad, sweep_bounds[2])
  } else if (sweep_type %in% c("exponential", "lin_exp")) {
    target_midpoints_pad <- append(target_midpoints_pad, exp(sweep_bounds[2]))
  }
  target_averaging_weights <- diff(target_midpoints_pad)


  sol_df <- data.frame(geometry = problem_data$geometry)
  for (tj in seq_along(target_list)) {
    this_target <- target_list[tj]
    scen_targets <- this_target * which_targets

    if (weighting_method == "target") {
      scen_targets <- scen_targets * (feature_weights / max(feature_weights))
      scen_targets[scen_targets > 1] <- 1
    }

    scen_problem <-
      problem(problem_data, theme_ids, cost_column = "cost") |>
      add_min_set_objective() |>
      add_relative_targets(scen_targets)

    if (weighting_method == "weight") {
      scen_problem <- scen_problem |>
        add_feature_weights(feature_weights)
    }

    scen_problem <- scen_problem |>
      add_binary_decisions() |>
      add_gap_portfolio(number_solutions = n_portfolio, pool_gap = 0.2)

    if (use_includes && any(problem_data$include)) {
      scen_problem <- scen_problem |> add_locked_in_constraints("include")
    }

    if (use_excludes && any(problem_data$exclude)) {
      scen_problem <- scen_problem |> add_locked_out_constraints("exclude")
    }

    scen_problem <- scen_problem |>
      add_default_solver(verbose = FALSE)


    scen_sol <- prioritizr_solve_safe(scen_problem, problem_data, n_portfolio)

    if (is.null(dim(scen_sol))) { # if prioritizr failed to converge to solution
      scen_sol <- problem_data
      for (ii in seq(n_portfolio)) {
        col_str <- paste0("solution_", ii)
        scen_sol[col_str] <- NA
      }
    }

    scen_sol["mean"] <- rowMeans(scen_sol |> dplyr::select(starts_with("solution")) |> st_drop_geometry())

    sol_df[paste0("target_", tj)] <- scen_sol$mean
  }

  sol_sf <- st_sf(sol_df)

  n_NA <- sum(is.na(colSums(sol_sf |> dplyr::select(starts_with("target_")) |> st_drop_geometry())))

  if (n_NA > 0) {
    warning(paste0(n_NA, " out of ", length(target_list), " runs in target sweep failed to converge and are being omitted from the ensemble average"))
  }

  sol_sf |>
    rowwise() |>
    mutate(mean = weighted.mean(c_across(starts_with("target")),
      target_averaging_weights,
      na.rm = TRUE
    ))
}

get_season_data <- function(spec_names) {
  eBird_data <- ebirdst::ebirdst_runs |> select(c(
    "species_code", "is_resident",
    "resident_start", "resident_end",
    "breeding_start", "breeding_end",
    "nonbreeding_start", "nonbreeding_end",
    "postbreeding_migration_start", "postbreeding_migration_end",
    "prebreeding_migration_start", "prebreeding_migration_end"
  ))

  spec_names <- merge(x = spec_names, y = eBird_data, by.x = "eBird_Abbrev", by.y = "species_code", all.x = TRUE, all.y = FALSE) |> subset(nchar(Priority) > 0)


  spec_names <- spec_names |> mutate(breeding_duration = ifelse(breeding_end - breeding_start > 0, breeding_end - breeding_start, breeding_end - breeding_start + 365))
  spec_names <- spec_names |> mutate(nonbreeding_duration = ifelse(nonbreeding_end - nonbreeding_start > 0, nonbreeding_end - nonbreeding_start, nonbreeding_end - nonbreeding_start + 365))
  spec_names <- spec_names |> mutate(postbreeding_migration_duration = ifelse(postbreeding_migration_end - postbreeding_migration_start > 0, postbreeding_migration_end - postbreeding_migration_start, postbreeding_migration_end - postbreeding_migration_start + 365))
  spec_names <- spec_names |> mutate(prebreeding_migration_duration = ifelse(prebreeding_migration_end - prebreeding_migration_start > 0, prebreeding_migration_end - prebreeding_migration_start, prebreeding_migration_end - prebreeding_migration_start + 365))
  spec_names <- spec_names |> mutate(resident_duration = ifelse(resident_end - resident_start > 0, resident_end - resident_start, resident_end - resident_start + 365))

  spec_names
}
